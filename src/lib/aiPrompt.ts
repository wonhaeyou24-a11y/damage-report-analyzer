import { STANDARD_PARTS } from "../types";

/**
 * 보고서 손상분석 AI 추출 프롬프트.
 * 특정 업체의 표 위치/번호를 하드코딩하지 않고, 문서 구조(본문/표/OCR/이미지)를
 * 분석하여 손상 그룹 → 개별 위치 → 부위/세부부위 정규화 순서로 처리하도록 지시한다.
 */
export function buildExtractionPrompt(reportText: string): string {
  return `당신은 사면/옹벽 등 시설물 점검 보고서에서 손상 정보를 구조화된 데이터로 추출하는 전문가입니다.

# 핵심 원칙 (반드시 준수)

1. 보고서에서 "손상 그룹"과 "개별 손상 위치"를 구분하라. 하나의 손상 그룹에 여러 위치가 나열되어 있는 경우 각각을 독립된 위치 항목으로 생성하라.
2. 동일한 손상명이라도 위치 또는 세부부위가 다르면 반드시 별도 위치 항목으로 생성하라.
3. 부위(part)와 세부부위(subPart)를 분리하라.
   - part는 다음 표준 분류값 중 하나만 사용하라: ${STANDARD_PARTS.join(", ")}
   - 보고서에 나타난 실제 시설명(예: 소단측구, 산마루측구, 도수로, 배수로 등)은 subPart에 저장하라. part 필드에 시설명을 넣지 마라.
4. 위치는 콤마로 나열된 개별 값은 각각 분리하되, "176~206m" 같은 범위는 하나의 위치로 유지하라. 임의로 범위를 잘게 쪼개지 마라.
5. 보고서에 명시되지 않은 규모/물량을 추정하거나 계산하지 마라.
6. 여러 개별 위치가 하나의 총 물량(그룹 합계)만 공유하는 경우, 각 위치에 총 물량을 반복하지 말고 quantityGroupTotal 필드 하나로 그룹 단위에 담아라. 특정 위치에만 명시적으로 대응되는 개별 물량이 있는 경우에만 해당 위치의 quantity에 넣어라.
7. 사진은 우선 손상 그룹 전체와의 1차 관계(그룹당 사진 수)만 photoCount로 기록하라. 특정 사진이 어느 개별 위치에 해당하는지 확실하지 않으면 임의로 연결하지 말고 비워두라(추후 별도 단계에서 사진 내용/캡션/페이지 위치로 매칭한다).
8. 각 손상 그룹은 원문 출처(페이지 번호, 유형: table/body/conclusion/photo 등, 가능하면 원문 발췌)를 sourceReferences에 남겨라.
9. 보고서 원문에 없는 정보를 절대 만들어내지 마라. 확실하지 않으면 필드를 null로 두거나 비워라.
10. 특정 업체의 표 번호나 페이지를 전제로 하지 말고, 문서 전체 구조(본문 설명, 표, OCR 텍스트, 사진대지)를 근거로 판단하라.

# 출력 형식

다음 JSON 스키마를 따르는 배열만 출력하라 (설명 텍스트 없이 JSON만):

[
  {
    "groupNo": "보고서 원문 그룹 번호 (예: ③), 없으면 순번 부여",
    "section": "구간 (예: 1구간)",
    "damageName": "손상명",
    "part": "표준 분류값 중 하나",
    "repairMethod": "보수방안",
    "quantityGroupTotal": "그룹 총 물량 (문자열, 예: '23.3m') 또는 null",
    "locations": [
      { "subPart": "세부부위 (없으면 '-')", "location": "개별 위치 (예: '165m' 또는 '176~206m')", "quantity": "이 위치에만 대응되는 개별 물량 또는 null" }
    ],
    "photoCount": "그룹에 연결된 사진 수 또는 null",
    "sourcePages": [80],
    "sourceReferences": [{ "page": 80, "type": "table", "excerpt": "원문 발췌 (가능한 경우)" }]
  }
]

# 분석 대상 보고서 텍스트

${reportText}
`;
}
